#if UNITY_EDITOR
using System.Collections;
using System.IO;
using NUnit.Framework;
using QuackQuack.Platform.Input;
using UnityEditor;
using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.InputSystem;
using UnityEngine.InputSystem.LowLevel;
using UnityEngine.InputSystem.UI;
using UnityEngine.TestTools;
using UnityEngine.UI;
using Object = UnityEngine.Object;
using TouchPhase = UnityEngine.InputSystem.TouchPhase;

namespace QuackQuack.Tests.PlayMode
{
    public class MobileTouchscreenTests
    {
        private GameObject root, eventObject;
        private EventSystem previousEvents;
        private bool previousEnabled;
        private Touchscreen screen, previousScreen;
        private InputSettings.BackgroundBehavior background;
        private InputSettings.EditorInputBehaviorInPlayMode editorInput;

        [UnitySetUp]
        public IEnumerator SetUp()
        {
            background = InputSystem.settings.backgroundBehavior;
            editorInput = InputSystem.settings.editorInputBehaviorInPlayMode;
            InputSystem.settings.backgroundBehavior = InputSettings.BackgroundBehavior.IgnoreFocus;
            InputSystem.settings.editorInputBehaviorInPlayMode = InputSettings.EditorInputBehaviorInPlayMode.AllDeviceInputAlwaysGoesToGameView;
            previousEvents = EventSystem.current;
            if (previousEvents != null) { previousEnabled = previousEvents.enabled; previousEvents.enabled = false; }
            eventObject = new GameObject("T066 touch events", typeof(EventSystem), typeof(InputSystemUIInputModule));
            eventObject.GetComponent<InputSystemUIInputModule>().AssignDefaultActions();
            previousScreen = Touchscreen.current; screen = InputSystem.AddDevice<Touchscreen>();
            var prefab = AssetDatabase.LoadAssetAtPath<GameObject>("Assets/QuackQuack/Prefabs/Prototype/MobileControls.prefab");
            Assert.That(prefab, Is.Not.Null, "Native mobile controls prefab must be generated by Unity.");
            root = Object.Instantiate(prefab);
            yield return null; yield return null;
            Canvas.ForceUpdateCanvases();
        }

        [UnityTearDown]
        public IEnumerator TearDown()
        {
            if (root != null) Object.Destroy(root);
            if (eventObject != null) Object.Destroy(eventObject);
            if (screen != null && screen.added) InputSystem.RemoveDevice(screen);
            if (previousScreen != null && previousScreen.added) previousScreen.MakeCurrent();
            InputSystem.settings.backgroundBehavior = background;
            InputSystem.settings.editorInputBehaviorInPlayMode = editorInput;
            yield return null;
            if (previousEvents != null) { previousEvents.enabled = previousEnabled; EventSystem.current = previousEvents; }
        }

        [UnityTest]
        public IEnumerator TouchscreenRaycastsDriveIndependentJoystickQuackAndPause()
        {
            var input = root.GetComponent<MobileInputAdapter>();
            var joystick = root.GetComponentInChildren<MobileJoystick>();
            var quack = root.transform.Find("QUACK"); var pause = root.transform.Find("PAUSAR");
            Assert.That(root.GetComponent<GraphicRaycaster>(), Is.Not.Null);
            Assert.That(root.GetComponent<CanvasScaler>().referenceResolution, Is.EqualTo(new Vector2(1920, 1080)));
            var center = Point(joystick.transform, Vector2.zero);
            var drag = Point(joystick.transform, new Vector2(60, 0));
            var quackPoint = Point(quack, Vector2.zero); var pausePoint = Point(pause, Vector2.zero);
            Touch(1, TouchPhase.Began, center); yield return null; yield return null;
            Touch(1, TouchPhase.Moved, drag); Touch(2, TouchPhase.Began, quackPoint);
            yield return null; yield return null;
            var command = input.Read();
            Assert.That(command.Move.x, Is.GreaterThan(0.5)); Assert.That(command.Move.y, Is.EqualTo(0).Within(0.01));
            Assert.That(command.QuackPressed, Is.True); Assert.That(command.PausePressed, Is.False);
            Assert.That(input.Read().QuackPressed, Is.False);
            Touch(2, TouchPhase.Ended, quackPoint); Touch(3, TouchPhase.Began, pausePoint);
            yield return null; yield return null;
            command = input.Read(); Assert.That(command.PausePressed, Is.True); Assert.That(command.Move.x, Is.GreaterThan(0.5));
            Touch(3, TouchPhase.Ended, pausePoint); Touch(1, TouchPhase.Ended, drag);
            yield return null; yield return null;
            command = input.Read(); Assert.That(command.Move, Is.EqualTo(Vector2.zero));
            Assert.That(command.QuackPressed || command.PausePressed, Is.False);
            Capture();
        }
        private void Touch(int id, TouchPhase phase, Vector2 position) => InputSystem.QueueStateEvent(screen,
            new TouchState { touchId = id, phase = phase, position = position });
        private static Vector2 Point(Transform rect, Vector2 local) => RectTransformUtility.WorldToScreenPoint(null, rect.TransformPoint(local));

        private void Capture()
        {
            var canvas = root.GetComponent<Canvas>();
            var cameraObject = new GameObject("T066 capture camera", typeof(Camera));
            var camera = cameraObject.GetComponent<Camera>(); camera.orthographic = true; camera.aspect = 1280f / 720;
            camera.clearFlags = CameraClearFlags.SolidColor; camera.backgroundColor = new Color(0.04f, 0.09f, 0.12f);
            var target = new RenderTexture(1280, 720, 24); var pixels = new Texture2D(1280, 720, TextureFormat.RGB24, false);
            var previous = RenderTexture.active;
            try
            {
                camera.targetTexture = target; canvas.renderMode = RenderMode.ScreenSpaceCamera; canvas.worldCamera = camera; canvas.planeDistance = 1;
                Canvas.ForceUpdateCanvases(); camera.Render(); RenderTexture.active = target;
                pixels.ReadPixels(new Rect(0, 0, 1280, 720), 0, 0); pixels.Apply();
                string path = Path.GetFullPath(Path.Combine(Application.dataPath, "../../../Logs/t066-controls.png"));
                Directory.CreateDirectory(Path.GetDirectoryName(path)); File.WriteAllBytes(path, pixels.EncodeToPNG());
            }
            finally
            {
                RenderTexture.active = previous; camera.targetTexture = null; canvas.renderMode = RenderMode.ScreenSpaceOverlay; canvas.worldCamera = null;
                target.Release(); Object.DestroyImmediate(target); Object.DestroyImmediate(pixels); Object.DestroyImmediate(cameraObject);
            }
        }
    }
}
#endif
